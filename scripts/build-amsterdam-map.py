#!/usr/bin/env python3
"""
Builds src/components/map/amsterdamMapData.ts from assets/map/amsterdam-source.svg.

The source is the illustration from the "Scenely Map Concepts" design canvas (board J). This script:
  - drops everything with text in it (place labels, banner, sign): the app draws labels itself,
    and the blueprint asks for no text inside illustrations;
  - drops the cyclist and the parked bike (the app animates its own, in the learner's colours);
  - expands <use> references into plain groups, so react-native-svg's SvgXml needs no <defs>;
  - samples the bike route into points, and notes where each place sits on it.

Run from the scenely folder:  python3 scripts/build-amsterdam-map.py
"""
import copy
import json
import math
import re
import xml.etree.ElementTree as ET

SRC = "assets/map/amsterdam-source.svg"
OUT = "src/components/map/amsterdamMapData.ts"
NS = "http://www.w3.org/2000/svg"
ET.register_namespace("", NS)

# Places in unlock order, and the route segment each one ends (see the route path's C/S commands).
STOPS = [("koffiebar", 0), ("supermarkt", 1), ("markt", 3), ("kleding", 4), ("huisarts", 6), ("ziekenhuis", 8), ("school", 9), ("station", 12)]


def q(tag):
    return f"{{{NS}}}{tag}"


def has_text(el):
    return any(e.tag == q("text") for e in el.iter())


raw = open(SRC).read()
if "xmlns=" not in raw[:300]:
    raw = raw.replace("<svg ", f'<svg xmlns="{NS}" ', 1)
root = ET.fromstring(raw)
defs = root.find(q("defs"))
library = {g.get("id"): g for g in defs}
root.remove(defs)

# Drop labels, banner, sign, north arrow text, the animated cyclist and the parked bike.
for el in list(root):
    if el.tag == q("g") and (has_text(el) or "{{" in (el.get("opacity") or "")):
        root.remove(el)
    elif el.get("id") == "leg":
        root.remove(el)

route_d = None
for el in root.iter():
    if el.get("id") == "route":
        route_d = el.get("d")
        del el.attrib["id"]


def expand(parent):
    for i, child in enumerate(list(parent)):
        if child.tag == q("use"):
            ref = (child.get("href") or "").lstrip("#")
            colour = re.search(r"color:\s*([^;]+)", child.get("style") or "")
            g = ET.Element(q("g"), {"transform": f"translate({child.get('x', '0')},{child.get('y', '0')})"})
            for part in library[ref]:
                part = copy.deepcopy(part)
                for e in part.iter():
                    for k, v in list(e.attrib.items()):
                        if v == "currentColor":
                            e.set(k, colour.group(1).strip() if colour else "#000")
                g.append(part)
            parent.remove(child)
            parent.insert(i, g)
        else:
            expand(child)


expand(root)
for k in ("role", "aria-label", "style"):
    root.attrib.pop(k, None)
xml = ET.tostring(root, encoding="unicode")
xml = re.sub(r"\s+", " ", xml).replace("> <", "><")

# --- sample the route (M, C and S commands only) ---
nums = lambda s: [float(n) for n in re.findall(r"-?\d+(?:\.\d+)?", s)]
cmds = re.findall(r"([MCS])([^MCS]*)", route_d)
x, y = nums(cmds[0][1])
points = [(x, y)]
seg_end = [0]
last_ctrl = None
for cmd, args in cmds[1:]:
    a = nums(args)
    step = 6 if cmd == "C" else 4
    for i in range(0, len(a), step):
        if cmd == "C":
            c1 = (a[i], a[i + 1]); c2 = (a[i + 2], a[i + 3]); end = (a[i + 4], a[i + 5])
        else:
            c1 = (2 * x - last_ctrl[0], 2 * y - last_ctrl[1]) if last_ctrl else (x, y)
            c2 = (a[i], a[i + 1]); end = (a[i + 2], a[i + 3])
        p0 = (x, y)
        for k in range(1, 25):
            t = k / 24
            u = 1 - t
            px = u**3 * p0[0] + 3 * u * u * t * c1[0] + 3 * u * t * t * c2[0] + t**3 * end[0]
            py = u**3 * p0[1] + 3 * u * u * t * c1[1] + 3 * u * t * t * c2[1] + t**3 * end[1]
            points.append((round(px, 1), round(py, 1)))
        seg_end.append(len(points) - 1)
        last_ctrl = c2
        x, y = end

stops = {pid: seg_end[seg] for pid, seg in STOPS}
w, h = int(root.get("width")), int(root.get("height"))

with open(OUT, "w") as f:
    f.write("// Generated by scripts/build-amsterdam-map.py from assets/map/amsterdam-source.svg. Do not edit by hand.\n\n")
    f.write("export type MapPoint = { x: number; y: number };\n\n")
    f.write(f"export const AMSTERDAM_WIDTH = {w};\nexport const AMSTERDAM_HEIGHT = {h};\n\n")
    f.write("/** The illustration, without labels or people. */\n")
    f.write(f"export const AMSTERDAM_XML = {json.dumps(xml, ensure_ascii=False)};\n\n")
    f.write("/** The bike route through every place, in unlock order. */\n")
    f.write("export const BIKE_ROUTE: readonly MapPoint[] = [\n")
    for px, py in points:
        f.write(f"  {{ x: {px:g}, y: {py:g} }},\n")
    f.write("];\n\n")
    f.write("/** Index in BIKE_ROUTE where each place sits. */\n")
    f.write(f"export const ROUTE_STOPS: Readonly<Record<string, number>> = {json.dumps(stops)};\n")

print(f"wrote {OUT}: {len(xml)} chars of SVG, {len(points)} route points, stops {stops}")
